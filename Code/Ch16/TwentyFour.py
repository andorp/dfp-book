def one_wire(word):
    c = zx.Circuit(1)
    for gate in word:
        c.add_gate(gate, 0)
    return c.to_graph()


def dot_on_wire(kind, phase):
    g = zx.Graph()
    i = g.add_vertex(VT.BOUNDARY, 0, 0)
    v = g.add_vertex(kind, 0, 1, phase=Fraction(phase))
    o = g.add_vertex(VT.BOUNDARY, 0, 2)
    g.add_edge((i, v))
    g.add_edge((v, o))
    g.set_inputs((i,))
    g.set_outputs((o,))
    return g, v


def sketchbook():
    # --- S, Z, X as spiders on a wire, exactly
    assert np.allclose(matrix_of(dot_on_wire(VT.Z, Fraction(1, 2))[0]), S)
    assert not np.allclose(matrix_of(dot_on_wire(VT.Z, Fraction(1, 2))[0]), S.conj().T)
    assert np.allclose(matrix_of(dot_on_wire(VT.Z, 1)[0]), Z)
    assert np.allclose(matrix_of(dot_on_wire(VT.X, 1)[0]), X)
    # Y = iXZ: read left to right, a green pi then a red pi, times i
    g = zx.Graph()
    i = g.add_vertex(VT.BOUNDARY, 0, 0)
    zg = g.add_vertex(VT.Z, 0, 1, phase=Fraction(1))
    xr = g.add_vertex(VT.X, 0, 2, phase=Fraction(1))
    o = g.add_vertex(VT.BOUNDARY, 0, 3)
    g.add_edge((i, zg))
    g.add_edge((zg, xr))
    g.add_edge((xr, o))
    g.set_inputs((i,))
    g.set_outputs((o,))
    assert np.allclose(matrix_of(g), X @ Z)                            # left to right: Z first
    g.scalar.add_phase(Fraction(1, 2))                                  # times i
    assert np.allclose(matrix_of(g), Y)
    assert not np.allclose(matrix_of(g), -Y)

    # --- CNOT = sqrt2 times the bare green-red pair (control on top)
    p = zx.Graph()
    i0, i1 = p.add_vertex(VT.BOUNDARY, 0, 0), p.add_vertex(VT.BOUNDARY, 1, 0)
    gz, rx = p.add_vertex(VT.Z, 0, 1), p.add_vertex(VT.X, 1, 1)
    o0, o1 = p.add_vertex(VT.BOUNDARY, 0, 2), p.add_vertex(VT.BOUNDARY, 1, 2)
    for a, b in [(i0, gz), (gz, o0), (i1, rx), (rx, o1), (gz, rx)]:
        p.add_edge((a, b))
    p.set_inputs((i0, i1))
    p.set_outputs((o0, o1))
    assert np.allclose(matrix_of(p), CNOT / np.sqrt(2))                  # bare: 1/sqrt2
    p.scalar.add_power(1)
    assert np.allclose(matrix_of(p), CNOT)
    c = zx.Circuit(2)
    c.add_gate("CNOT", 0, 1)
    assert same_picture(c.to_graph(), p)                                # pyzx's CNOT agrees

    # --- the 24 as one-wire pictures of H and S: every turn a multiple of a quarter,
    #     and the 24 pictures distinct up to a phase
    group = clifford_24()
    keys = set()
    for U, word in group.values():
        g = one_wire(word)
        M = matrix_of(g)
        assert np.allclose(M, U)                                        # the picture is the gate
        assert all(Fraction(g.phase(v)).denominator <= 2 for v in g.vertices())
        assert all(g.type(v) in (VT.BOUNDARY, VT.Z, VT.X) for v in g.vertices())
        keys.add(key(rotation(M)))
    assert len(keys) == 24

    # --- the "over" is colour change (Theorem 8.2, row 58): a green pi between two yellow
    #     boxes is a red pi, exactly: HZH = X
    boxed = zx.Graph()
    i = boxed.add_vertex(VT.BOUNDARY, 0, 0)
    v = boxed.add_vertex(VT.Z, 0, 1, phase=Fraction(1))
    o = boxed.add_vertex(VT.BOUNDARY, 0, 2)
    boxed.add_edge((i, v), ET.HADAMARD)
    boxed.add_edge((v, o), ET.HADAMARD)
    boxed.set_inputs((i,))
    boxed.set_outputs((o,))
    red, rv = dot_on_wire(VT.X, 1)
    assert same_picture(boxed, red)
    assert not same_picture(dot_on_wire(VT.Z, 1)[0], red)               # without the boxes: no
    # DERIVED: the colour-change rule applied to the red pi gives the boxed green pi
    h = red.copy()
    assert simp.check_color_change(h, rv) and simp.color_change(h, rv)
    assert h.type(rv) == VT.Z and h.phase(rv) == 1
    assert all(h.edge_type(e) == ET.HADAMARD for e in h.incident_edges(rv))
    assert same_picture(h, boxed) and same_picture(h, red)


