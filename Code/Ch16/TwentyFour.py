MOVE = {"quarter": S, "back": S.conj().T, "over": H}


def blackboard():
    # --- the letters: Y = iXZ, squares, anticommutation, products
    assert np.allclose(Y, [[0, -1j], [1j, 0]])
    for P in PAULI:
        assert np.allclose(P @ P, I2)
    for A_, B_ in [(X, Y), (Y, Z), (Z, X)]:
        assert np.allclose(A_ @ B_, -B_ @ A_)
    assert np.allclose(X @ Y, 1j * Z) and np.allclose(Y @ Z, 1j * X) and np.allclose(Z @ X, 1j * Y)

    # --- Result 16.1: |P_n| = 4 * 4^n, by enumeration (n = 1 is computed; code is exempt)
    for n in (1, 2, 3):
        group = pauli_group(n)
        assert len(group) == 4 * 4 ** n
    assert len(pauli_group(2)) == 64 and len(pauli_group(3)) == 256
    # any two commute or anticommute; they anticommute iff the number of wires where both
    # letters are non-I and different is odd -- every pair of strings, n = 2 and n = 3
    letters = [I2, X, Y, Z]
    for n in (2, 3):
        strings = list(product(range(4), repeat=n))
        mats = {s: kron(*[letters[c] for c in s]) for s in strings}
        for s in strings:
            for t in strings:
                A_, B_ = mats[s], mats[t]
                clash = sum(1 for a, b in zip(s, t) if a and b and a != b)
                assert np.allclose(A_ @ B_, (-1) ** clash * B_ @ A_)
    # the two-wire example: X(x)Z and Z(x)X commute; X(x)I and Z(x)X anticommute
    assert np.allclose(kron(X, Z) @ kron(Z, X), kron(Z, X) @ kron(X, Z))
    assert np.allclose(kron(X, I2) @ kron(Z, X), -kron(Z, X) @ kron(X, I2))

    # --- the three familiar Cliffords (Gottesman's Table 1)
    assert np.allclose(H @ X @ H.conj().T, Z) and np.allclose(H @ Z @ H.conj().T, X)
    assert np.allclose(H @ Y @ H.conj().T, -Y)
    assert np.allclose(S @ X @ S.conj().T, Y) and np.allclose(S @ Y @ S.conj().T, -X)
    assert np.allclose(S @ Z @ S.conj().T, Z)
    assert not np.allclose(S @ X @ S.conj().T, -Y)                   # S, not S^dagger
    C = CNOT
    assert np.allclose(C @ kron(X, I2) @ C, kron(X, X)) and np.allclose(C @ kron(I2, X) @ C, kron(I2, X))
    assert np.allclose(C @ kron(Z, I2) @ C, kron(Z, I2)) and np.allclose(C @ kron(I2, Z) @ C, kron(Z, Z))
    assert not np.allclose(C @ kron(I2, Z) @ C, kron(I2, Z))          # control on TOP

    # --- Result 16.2: the twenty-four
    group = clifford_24()
    assert len(group) == 24
    rots = {k for k in group}
    for U, _ in group.values():
        assert np.allclose(U @ U.conj().T, I2)
        # a Clifford: every Pauli goes to a signed Pauli
        for P in PAULI:
            img = U @ P @ U.conj().T
            assert any(np.allclose(img, s * Q) for s in (1, -1) for Q in PAULI)
        R = rotation(U)
        assert np.allclose(R, np.rint(R))                               # a signed permutation...
        assert sorted(np.abs(np.rint(R)).sum(axis=0)) == [1, 1, 1]
        assert sorted(np.abs(np.rint(R)).sum(axis=1)) == [1, 1, 1]
        assert np.isclose(np.linalg.det(R), 1)                          # ...of determinant +1
    # every rotation of the octahedron occurs: the 24 signed permutations with det +1
    octa = set()
    for perm in permutations(range(3)):
        for signs in product((1, -1), repeat=3):
            M = np.zeros((3, 3))
            for i, j in enumerate(perm):
                M[i, j] = signs[i]
            if np.isclose(np.linalg.det(M), 1):
                octa.add(key(M))
    assert len(octa) == 24 and rots == octa
    # different elements give different rotations: two unitaries with the same rotation
    # differ by a W commuting with X and Z, and such a W is a multiple of I.  Checked as a
    # linear-algebra fact (the commutant of {X, Z} is one-dimensional) and on a generic W.
    A = np.zeros((8, 4), dtype=complex)
    for k in range(4):
        E = np.zeros(4, dtype=complex)
        E[k] = 1
        W = E.reshape(2, 2)
        A[:, k] = np.concatenate([(X @ W - W @ X).ravel(), (Z @ W - W @ Z).ravel()])
    assert 4 - np.linalg.matrix_rank(A) == 1
    rng = np.random.default_rng(1601)
    W = random_matrix(rng)
    assert not np.allclose(X @ W, W @ X) or not np.allclose(Z @ W, W @ Z)
    # the phase is invisible to the rotation, so "up to a phase" is what is counted
    U0 = group[key(rotation(H @ S))][0]
    assert key(rotation(np.exp(1j * rng.uniform(0, 2 * np.pi)) * U0)) == key(rotation(U0))
    # the trap: six up times five front is thirty, but only 24 (up, front) pairs are seatings
    pairs = {seating(U) for U, _ in group.values()}
    assert len(pairs) == 24 and 6 * 5 == 30 != len(pairs) == 6 * 4
    assert "Dark green up, pale green front." not in pairs              # opposite tip: never

    # --- the half-turns are the Paulis: diagonal rotations, entries +-1; from home exactly
    #     four seatings keep every tip in its own place or its opposite's
    for P in PAULI:
        R = np.rint(rotation(P))
        assert np.allclose(R, np.diag(np.diag(R))) and set(np.abs(np.diag(R))) == {1}
        assert sorted(np.diag(R)) == [-1, -1, 1]
    assert sum(1 for U, _ in group.values()
               if np.allclose(np.rint(rotation(U)), np.diag(np.diag(np.rint(rotation(U)))))) == 4

    # --- the octahedron caption: HXH^dagger = Z (over: front tip up); SXS^dagger = Y
    #     (quarter: front tip to the right)
    assert seating(I2) == "Dark green up, dark red front."
    assert np.allclose(rotation(H) @ [1, 0, 0], [0, 0, 1])
    assert np.allclose(rotation(S) @ [1, 0, 0], [0, 1, 0])
    # one quarter from home: the dark red goes right, the pale gold comes to the front
    assert seating(S) == "Dark green up, pale gold front."
    assert seating(S.conj().T) == "Dark green up, dark gold front."     # back, not quarter
    # over: top and front change places, left and right change places
    assert seating(H) == "Dark red up, dark green front."

    # --- the walk (the preludes): each move multiplies on the left
    U, seen = I2, []
    for mv in WALK_MOVES:
        seen.append(seating(U))
        U = MOVE[mv] @ U
    assert seen == WALK_NAMES                                           # the card's 24, in order
    assert len(set(seen)) == 24                                         # every key once
    assert key(rotation(U)) == key(rotation(I2))                        # and home again
    assert seating(U) == "Dark green up, dark red front."
    # each tip is up for four seatings in a row: six groups of four
    ups = [s.split(" up")[0] for s in seen]
    assert [ups[4 * k:4 * k + 4].count(ups[4 * k]) for k in range(6)] == [4] * 6

    # --- quarter and over alone: no walk through all 24 that comes home (exhaustive)
    Rs, Rh = np.rint(rotation(S)), np.rint(rotation(H))
    home = key(np.eye(3))

    def walks(moves):
        """(closed walks, all walks) through all 24 seatings from home, each seating once."""
        tally = [0, 0]

        def rec(last, visited):
            if len(visited) == 24:
                tally[1] += 1
                tally[0] += int(any(key(M @ last) == home for M in moves))
                return
            for M in moves:
                k = key(M @ last)
                if k not in visited:
                    visited.add(k)
                    rec(M @ last, visited)
                    visited.remove(k)

        rec(np.eye(3), {home})
        return tuple(tally)

    assert walks((Rs, Rh)) == (0, 6)                  # six open paths, none comes home
    closed, _ = walks((Rs, Rh, Rs.T))                 # with back: closed walks exist,
    assert closed > 0                                 # and the Crab's is one of them (above)

    pictures()


