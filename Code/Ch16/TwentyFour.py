# the places of the room as signed Paulis (card section 4): front +X, right +Y, back -X,
# left -Y, up +Z, socket -Z; a tip is a signed Pauli: dark +, pale -; red X, gold Y, green Z
PLACE = {"front": (0, +1), "right": (1, +1), "back": (0, -1), "left": (1, -1), "up": (2, +1), "socket": (2, -1)}
TIPNAME = {v: k for k, v in TIP.items()}


def tip_in_lug(U, place):
    """The tip in the lug at `place` when the moves compose to U: U^dagger P U = +-Q, a signed
    Pauli, named.  (U carries the tip P_j to U P_j U^dagger.)"""
    i, s = PLACE[place]
    M = U.conj().T @ (s * PAULI[i]) @ U
    found = [(j, t) for j in range(3) for t in (1, -1) if np.allclose(M, t * PAULI[j])]
    assert len(found) == 1, place                           # always +- a Pauli: a Clifford
    return TIP[found[0]]


def compose(moves, start):
    """U for a picture: the start seating's element of the twenty-four, then each move
    multiplied on the LEFT.  A half about a coloured line is the half-turn about where that
    line lies now: the Pauli U P U^dagger, on the left, which is U P on the right."""
    group = clifford_24()
    name = seating(I2) if start == "home" else start + "."
    found = [V for V, _ in group.values() if seating(V) == name]
    assert len(found) == 1, start
    U = found[0]
    line = {"red": X, "gold": Y, "green": Z}
    for mv in [m.strip() for m in moves.split(",") if m.strip()]:
        if mv.startswith("a half about the "):
            P_ = line[mv.split()[4]]
            U = (U @ P_ @ U.conj().T) @ U
        else:
            U = MOVE[mv] @ U
    return U


def read_dump(dump):
    """A seated dump's places: {place: tip}."""
    words = dump.split(" ", 1)
    assert words[0] == "seated"
    return dict(kv.split("=") for kv in re.split(r" (?=\w+=)", words[1]))


