"""Challenge III: Half a Touch  (re-tying; local complementation; the pivot)
=========================================================================
"A tie lost moved the number one way, and a tie gained moves it back. Two halves of a touch make a touch, and two re-tyings make no change."  -- Tortoise

Claim: for every graph G and vertex a, U^tau_a = e^{-i pi/4 X_a} prod_{b in N_a} e^{i pi/4 Z_b}
sends |G> to exactly e^{i pi (|N_a|-1)/4} |tau_a(G)>, and (U^tau_a)^2 = i^{|N_a|-1} K_a
(Result 16.8); as clip rings (red quarter round on a, green quarter back on each neighbour,
or the reverse) half a touch sends |G> to exactly |tau_a(G)>, and on nets
(net of G with the rings) = 2^{(|E'|-|E|)/2} (net of tau_a(G)) (Result 16.9); for every
edge uv, H_u H_v Z_{N_u cap N_v} |G> = |G ^ uv> with no phase (Result 16.10); the stabilizer
states number 2^n prod (2^{n-k}+1) and each is a graph state with a one-wire Clifford on
each wire (Result 16.11, checked for n <= 3).
"""
