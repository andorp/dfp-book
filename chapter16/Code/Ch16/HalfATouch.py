AT_REST = (VT.Z, 0)


def net(n, E, clips=None, boxed=(), caps=None):
    """The net of E: a phase-free green spider per bell, a Hadamard edge per tie.  clips puts
    a clip ring (kind, phase) on each output; `boxed` bells get a yellow box (a Hadamard
    edge) on their output; `caps` = {bell: phase} closes those outputs with a green effect."""
    g = zx.Graph()
    bells = [g.add_vertex(VT.Z, w, 1) for w in range(n)]
    for b, c in E:
        g.add_edge((bells[b], bells[c]), ET.HADAMARD)
    outs = []
    for w in range(n):
        last = bells[w]
        if clips is not None:
            kind, phase = clips[w]
            r = g.add_vertex(kind, w, 2, phase=Fraction(phase))
            g.add_edge((last, r))
            last = r
        if caps is not None and w in caps:
            c = g.add_vertex(VT.Z, w, 3, phase=Fraction(caps[w]))
            g.add_edge((last, c))
            continue
        o = g.add_vertex(VT.BOUNDARY, w, 4)
        g.add_edge((last, o), ET.HADAMARD if w in boxed else ET.SIMPLE)
        outs.append(o)
    g.set_inputs(())
    g.set_outputs(tuple(outs))
    return g, bells


def times(g, power=0, phase=0):
    """g times sqrt2^power times e^{i pi phase}."""
    h = g.copy()
    h.scalar.add_power(power)
    h.scalar.add_phase(Fraction(phase))
    return h


def half_touch(n, E, a, reverse=False):
    q = Fraction(1, 2)
    clips = [AT_REST] * n
    clips[a] = (VT.X, -q if reverse else q)
    for b in nbrs(E, a):
        clips[b] = (VT.Z, q if reverse else -q)
    return clips


def sketchbook():
    rng = np.random.default_rng(1623)
    n = 5

    # --- Result 16.9 on nets: at the left-back bell 2^{-1/2}, at the knot 2
    for a, e2, factor in [(0, 5, 2 ** -0.5), (KNOT, 8, 2.0)]:
        Et = tau(BOWTIE, a)
        assert len(Et) == e2 and np.isclose(2 ** ((len(Et) - len(BOWTIE)) / 2), factor)
        target = times(net(n, Et)[0], len(Et) - len(BOWTIE))           # sqrt2^{e'-e}
        for rev in (False, True):
            clipped = net(n, BOWTIE, half_touch(n, BOWTIE, a, rev))[0]
            assert same_picture(clipped, target)
            assert np.allclose(matrix_of(clipped).ravel(),
                               factor * 2 ** ((n - len(Et)) / 2) * graph_state(n, Et))
            assert not same_picture(clipped, net(n, Et)[0])             # the number is drawn
        # both clips turned the same way: not a re-tying
        wrong = [AT_REST] * n
        wrong[a] = (VT.X, Fraction(1, 2))
        for b in nbrs(BOWTIE, a):
            wrong[b] = (VT.Z, Fraction(1, 2))
        assert not same_picture(net(n, BOWTIE, wrong)[0], target)
    # the second re-tying at the same bell undoes the first: 2^{-1/2} then 2^{+1/2}
    E1 = tau(BOWTIE, 0)
    assert same_picture(net(n, E1, half_touch(n, E1, 0))[0],
                        times(net(n, BOWTIE)[0], len(BOWTIE) - len(E1)))
    # random graphs, every vertex, both ways round
    for _ in range(25):
        m = int(rng.integers(1, 7))
        E = random_graph(rng, m)
        for a in range(m):
            Et = tau(E, a)
            for rev in (False, True):
                assert same_picture(net(m, E, half_touch(m, E, a, rev))[0],
                                    times(net(m, Et)[0], len(Et) - len(E)))

    # --- half a touch twice: two quarter clips on a ring fuse (row 57) into the safe touch,
    #     which the net does not notice
    g, bells = net(n, BOWTIE, half_touch(n, BOWTIE, 0))
    before = g.copy()
    rings = {}
    for w in range(n):
        (o,) = [v for v in g.neighbors(bells[w]) if g.type(v) != VT.BOUNDARY and g.row(v) == 2]
        rings[w] = o
    for w, (kind, phase) in enumerate(half_touch(n, BOWTIE, 0)):
        if phase:
            (out,) = [v for v in g.neighbors(rings[w]) if g.type(v) == VT.BOUNDARY]
            g.remove_edge(g.edge(rings[w], out))
            second = g.add_vertex(kind, w, 2.5, phase=Fraction(phase))
            g.add_edge((rings[w], second))
            g.add_edge((second, out))
            assert simp.check_fuse(g, rings[w], second) and simp.fuse(g, rings[w], second)
            assert g.phase(rings[w]) == 1                               # a quarter and a quarter: a half
    assert same_picture(g, net(n, BOWTIE)[0])                           # the whole touch: unnoticed
    assert not same_picture(before, net(n, BOWTIE)[0])                  # half of it: noticed

    # --- Result 16.10 on nets: yellow boxes on u's and v's outputs, green pi on the common
    #     neighbours' = 2^{(|E''|-|E|)/2} net of G ^ uv.  The bow tie along 1-3, then random.
    cases = [(n, BOWTIE, 0, KNOT)]
    for _ in range(15):
        m = int(rng.integers(2, 7))
        E = random_graph(rng, m)
        cases += [(m, E, u, v) for u, v in E]
    for m, E, u, v in cases:
        Ep = pivot(E, u, v)
        C = set(nbrs(E, u)) & set(nbrs(E, v))
        clips = [(VT.Z, 1) if w in C else AT_REST for w in range(m)]
        lhs = net(m, E, clips, boxed=(u, v))[0]
        assert same_picture(lhs, times(net(m, Ep)[0], len(Ep) - len(E)))
        if C:
            assert not same_picture(net(m, E, [AT_REST] * m, boxed=(u, v))[0],
                                    times(net(m, Ep)[0], len(Ep) - len(E)))

    # --- the interior form, DERIVED by the rewrite (Duncan et al. Lemma 5.2): close the
    #     left-back bell's output with a green quarter-round effect; spider_simp fuses it in,
    #     and lcomp_simp pulls the interior quarter out: its neighbours are re-tied and turned a
    #     quarter back, and the number e^{i pi/4}/2 is set aside.  The boundary form above is
    #     checked by matrix, not derived here (the chapter's deviation (f)).
    g, _ = net(n, BOWTIE, caps={0: Fraction(1, 2)})
    h = g.copy()
    assert simp.spider_simp(h)
    interior = [v for v in h.vertices() if h.type(v) == VT.Z and h.phase(v) == Fraction(1, 2)]
    assert len(interior) == 1 and all(h.type(w) != VT.BOUNDARY for w in h.neighbors(interior[0]))
    assert simp.lcomp_simp(h)
    assert same_picture(h, g)
    assert h.num_vertices() == 4 + 4                                    # four bells, four outputs
    # the picture it leaves: bells 1..4 tied as tau_0(G) without bell 0, the neighbours
