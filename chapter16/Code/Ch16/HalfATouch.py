X = np.array([[0, 1], [1, 0]], dtype=complex)
Z = np.diag([1, -1]).astype(complex)
Y = 1j * X @ Z
H = np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2)
S = np.diag([1, 1j])
PLUS = np.array([1, 1], dtype=complex) / np.sqrt(2)
MINUS = np.array([1, -1], dtype=complex) / np.sqrt(2)
XQ = (I2 - 1j * X) / np.sqrt(2)          # e^{-i pi/4 X}: a quarter about X
ZQ = (I2 + 1j * Z) / np.sqrt(2)          # e^{+i pi/4 Z}: a quarter about Z

BOWTIE = [(0, 1), (0, 2), (1, 2), (2, 3), (2, 4), (3, 4)]   # 0 left-back ... 2 knot ... 4 right-front
KNOT = 2


def on(n, ops):
    return kron(*[ops.get(w, I2) for w in range(n)])


def nbrs(E, a):
    return sorted({v for e in E for v in e if a in e and v != a})


def norm(E):
    return sorted(tuple(sorted(e)) for e in E)


def graph_state(n, E):
    amps = [(-1) ** sum(((x >> (n - 1 - b)) & 1) * ((x >> (n - 1 - c)) & 1) for b, c in E)
            for x in range(2 ** n)]
    return np.array(amps, dtype=complex) / 2 ** (n / 2)


def K(n, E, a):
    ops = {b: Z for b in nbrs(E, a)}
    ops[a] = X
    return on(n, ops)


def tau(E, a):
    """Local complement at a: complement the ties among the neighbours of a."""
    N = nbrs(E, a)
    Es = set(norm(E))
    for b, c in combinations(N, 2):
        Es ^= {(b, c)}
    return sorted(Es)


def pivot(E, u, v):
    return tau(tau(tau(E, u), v), u)


def U_tau(n, E, a):
    ops = {b: ZQ for b in nbrs(E, a)}
    ops[a] = XQ
    return on(n, ops)


def random_graph(rng, n):
    return [e for e in combinations(range(n), 2) if rng.random() < 0.5]


def canon(v):
    """A state up to a global phase: divide by the phase of its first non-zero entry."""
    k = int(np.argmax(np.abs(v) > 1e-9))
    return tuple(np.round(v * abs(v[k]) / v[k], 8))


def stabilizer_states(n):
    """Every state reachable from |0...0> by H, S on any wire and CNOT on any ordered pair."""
    gates = []
    for w in range(n):
        gates += [on(n, {w: H}), on(n, {w: S})]
    for c, t in product(range(n), repeat=2):
        if c != t:
            M = np.zeros((2 ** n, 2 ** n), dtype=complex)
            for x in range(2 ** n):
                y = x ^ (1 << (n - 1 - t)) if (x >> (n - 1 - c)) & 1 else x
                M[y, x] = 1
            gates.append(M)
    start = np.zeros(2 ** n, dtype=complex)
    start[0] = 1
    seen, frontier = {canon(start): start}, [start]
    while frontier:
        nxt = []
        for v in frontier:
            for M in gates:
                w = M @ v
                if canon(w) not in seen:
                    seen[canon(w)] = w
                    nxt.append(w)
        frontier = nxt
    return list(seen.values())


def local_cliffords():
    """The 24 one-wire Cliffords, one per rotation (generated by H and S)."""
    found, frontier = {}, [I2]
    rot = lambda U: tuple(np.rint([[np.trace(P @ U @ Q @ U.conj().T).real / 2 for Q in (X, Y, Z)]
                                   for P in (X, Y, Z)]).astype(int).ravel())
    found[rot(I2)] = I2
    while frontier:
        nxt = []
        for U in frontier:
            for M in (H, S):
                V = M @ U
                if rot(V) not in found:
                    found[rot(V)] = V
                    nxt.append(V)
        frontier = nxt
    return list(found.values())


def blackboard():
    rng = np.random.default_rng(1603)
    n = 5
    G = graph_state(n, BOWTIE)

    # --- the worked example: a = the left-back bell (0), neighbours 1 and 2
    assert np.allclose(XQ @ Z @ XQ.conj().T, -1j * X @ Z)              # e^{-i pi/4 X} Z e^{i pi/4 X} = -iXZ
    assert np.allclose(ZQ @ X @ ZQ.conj().T, 1j * Z @ X)               # e^{i pi/4 Z} X e^{-i pi/4 Z} = iZX
    U = U_tau(n, BOWTIE, 0)
    img = U @ K(n, BOWTIE, 1) @ U.conj().T
    assert np.allclose(img, on(n, {0: X @ Z, 1: Z @ X, 2: Z}))
    assert not any(np.allclose(img, K(n, BOWTIE, b)) for b in range(n))  # not a safe touch of the bow tie
    E1 = tau(BOWTIE, 0)
    assert E1 == norm([(0, 1), (0, 2), (2, 3), (2, 4), (3, 4)])           # the tie 2-3 (1-2 here) is gone
    assert np.allclose(img, K(n, E1, 0) @ K(n, E1, 1))                  # = K'_1 K'_2

    # --- local complement: twice undoes it; at the knot, six ties become eight
    assert tau(tau(BOWTIE, 0), 0) == norm(BOWTIE)
    Ek = tau(BOWTIE, KNOT)
    assert Ek == norm([(0, 2), (1, 2), (2, 3), (2, 4), (0, 3), (0, 4), (1, 3), (1, 4)])
    assert len(Ek) == 8 and len(E1) == 5

    # --- Result 16.8, exact, with its phase: every bell of the bow tie, then random graphs
    cases = [(n, BOWTIE, a) for a in range(n)]
    for _ in range(100):
        m = int(rng.integers(1, 7))
        cases.append((m, random_graph(rng, m), int(rng.integers(m))))
    for m, E, a in cases:
        Gs, Et = graph_state(m, E), tau(E, a)
        assert tau(Et, a) == norm(E)                                    # tau twice = id
        d = len(nbrs(E, a))
        Ua = U_tau(m, E, a)
        phase = np.exp(1j * np.pi * (d - 1) / 4)
        assert np.allclose(Ua @ Gs, phase * graph_state(m, Et))
        if (d - 1) % 8:
            assert not np.allclose(Ua @ Gs, graph_state(m, Et))         # the phase is load-bearing
        # (U^tau_a)^2 = i^{|N_a|-1} K_a
        assert np.allclose(Ua @ Ua, 1j ** (d - 1) * K(m, E, a))
        if (d - 1) % 4:
            assert not np.allclose(Ua @ Ua, K(m, E, a))
        # the proof, operator by operator: K_c -> K'_c off the neighbourhood (a included),
        # K_b -> K'_a K'_b on it
        for c in range(m):
            img = Ua @ K(m, E, c) @ Ua.conj().T
            if c in nbrs(E, a):
                assert np.allclose(img, K(m, Et, a) @ K(m, Et, c))
            else:
                assert np.allclose(img, K(m, Et, c))
        # every graph state has <0...0|G> = 2^{-n/2}
        assert np.isclose(Gs[0], 2 ** (-m / 2))
    # two halves of the touch make the touch: -i K at the knot, i K at a wing bell
    assert np.allclose(np.linalg.matrix_power(U_tau(n, BOWTIE, KNOT), 2), -1j * K(n, BOWTIE, KNOT))
    assert np.allclose(np.linalg.matrix_power(U_tau(n, BOWTIE, 0), 2), 1j * K(n, BOWTIE, 0))

    # --- the clip rings as matrices: red pi/2 with two legs = e^{i pi/4} e^{-i pi/4 X};
    #     green -pi/2 = diag(1, -i) = e^{-i pi/4} e^{i pi/4 Z}
    plus, minus = np.array([1, 1]) / np.sqrt(2), np.array([1, -1]) / np.sqrt(2)
    red_q = np.outer(plus, plus) + 1j * np.outer(minus, minus)
    green_qb = np.diag([1, -1j])
    assert np.allclose(red_q, np.exp(1j * np.pi / 4) * XQ)
    assert np.allclose(green_qb, np.exp(-1j * np.pi / 4) * ZQ)
    red_qb, green_q = red_q.conj(), np.diag([1, 1j])                   # the reverse turns
    # Result 16.9 on the blackboard: half a touch as clip rings sends |G> to exactly |tau_a G>
    for m, E, a in cases:
        Gs, Gt = graph_state(m, E), graph_state(m, tau(E, a))
        N = nbrs(E, a)
        fwd = on(m, {**{b: green_qb for b in N}, a: red_q})
        rev = on(m, {**{b: green_q for b in N}, a: red_qb})
        assert np.allclose(fwd @ Gs, Gt)
        assert np.allclose(rev @ Gs, Gt)
        if N:
            same_way = on(m, {**{b: green_q for b in N}, a: red_q})    # both turned round: no
            assert not np.allclose(same_way @ Gs, Gt)

    # --- the LC orbit of the bow tie: every graph reached is a net, and the state follows
    #     the phase law along the way (the GSLC picture: local turns only re-tie)
    orbit, frontier = {tuple(norm(BOWTIE))}, [norm(BOWTIE)]
    while frontier:
        nxt = []
        for E in frontier:
            for a in range(n):
                Et = tau(E, a)
                d = len(nbrs(E, a))
                assert np.allclose(U_tau(n, E, a) @ graph_state(n, E),
                                   np.exp(1j * np.pi * (d - 1) / 4) * graph_state(n, Et))
                if tuple(Et) not in orbit:
                    orbit.add(tuple(Et))
                    nxt.append(Et)
        frontier = nxt
    assert len(orbit) > 1

    # --- Result 16.10, the pivot: G ^ uv = tau_u tau_v tau_u (G), symmetric in u and v;
    #     H_u H_v Z_C |G> = |G ^ uv> with no phase.  The bow tie along 1-3 (0-2 here):
    Ep = pivot(BOWTIE, 0, KNOT)
    assert Ep == norm([(0, 1), (0, 2), (0, 3), (0, 4), (1, 2), (1, 3), (1, 4), (3, 4)])
    assert np.allclose(on(n, {0: H, KNOT: H, 1: Z}) @ G, graph_state(n, Ep))
    assert not np.allclose(on(n, {0: H, KNOT: H}) @ G, graph_state(n, Ep))   # Z_C is needed
    # the three unitaries, wire by wire: each is -YH
    assert np.allclose(XQ @ ZQ @ XQ, -Y @ H) and np.allclose(ZQ @ XQ @ ZQ, -Y @ H)
    assert np.allclose(ZQ @ ZQ, 1j * Z)
    for _ in range(80):
        m = int(rng.integers(2, 7))
        E = random_graph(rng, m)
        for u, v in E:
            Ep = pivot(E, u, v)
            assert Ep == pivot(E, v, u)                                 # symmetric
            Nu, Nv = set(nbrs(E, u)) - {v}, set(nbrs(E, v)) - {u}
            A, B, C = Nu - Nv, Nv - Nu, Nu & Nv
            # it complements A-B, A-C, B-C and exchanges the neighbourhoods of u and v
            want = set(norm(E))
            for P, Q in [(A, B), (A, C), (B, C)]:
                for p in P:
                    for q in Q:
                        want ^= {tuple(sorted((p, q)))}
            for w in A | B | C:
                for x in (u, v):
                    want.discard(tuple(sorted((w, x))))
            for w in (B | C):
                want.add(tuple(sorted((u, w))))
            for w in (A | C):
                want.add(tuple(sorted((v, w))))
            assert sorted(want) == Ep
            Gs = graph_state(m, E)
            lhs = on(m, {**{c: Z for c in C}, u: H, v: H}) @ Gs
            assert np.allclose(lhs, graph_state(m, Ep))                 # phase 1, exactly
            if C:
                assert not np.allclose(on(m, {u: H, v: H}) @ Gs, graph_state(m, Ep))

    # --- Result 16.11 (stated): the count, and the GSLC form, checked for small n
    ag = lambda n_: 2 ** n_ * int(np.prod([2 ** (n_ - k) + 1 for k in range(n_)]))
    states = {}
    for m, count in [(1, 6), (2, 60), (3, 1080)]:
        states[m] = stabilizer_states(m)
        assert len(states[m]) == count == ag(m)
    assert ag(5) == 2423520
    # (iii) each is fixed by exactly 2^n signed Pauli strings (n = 1, 2)
    letters = [I2, X, Y, Z]
    for m in (1, 2):
        paulis = [s * kron(*[letters[c] for c in word])
                  for word in product(range(4), repeat=m) for s in (1, -1)]
        for v in states[m]:
            assert sum(1 for P in paulis if np.allclose(P @ v, v)) == 2 ** m
    # the one-wire six are the octahedron's tips: fixed by +-X, +-Y or +-Z
    for v in states[1]:
        assert sum(1 for P in (X, Y, Z) for s in (1, -1) if np.allclose(s * P @ v, v)) == 1
    # every stabilizer state is a graph state with a one-wire Clifford on each wire (n = 2, 3)
    LC = np.array(local_cliffords())
    assert len(LC) == 24
    for m in (2, 3):
        gslc = set()
        for E in [list(c) for r in range(m * (m - 1) // 2 + 1)
                  for c in combinations(list(combinations(range(m), 2)), r)]:
            T = graph_state(m, E).reshape([2] * m)
            if m == 2:
                vecs = np.einsum("aij,bkl,jl->abik", LC, LC, T).reshape(-1, 4)
            else:
                vecs = np.einsum("aij,bkl,cpq,jlq->abcikp", LC, LC, LC, T).reshape(-1, 8)
            for v in vecs:
                gslc.add(canon(v))
        assert {canon(v) for v in states[m]} == gslc


    pictures()


